"""Recorded login attempts, so the rate limiter has something to count."""
from alembic import op


revision = '0002_login_attempts'
down_revision = '0001_postgres'
branch_labels = None
depends_on = None


def upgrade():
    connection = op.get_bind()
    # Deliberately separate from audit_log: this table is swept continuously
    # and holds only what a limiter needs, while the audit trail is evidence
    # and must not be deleted by a maintenance job.
    connection.exec_driver_sql("""
        CREATE TABLE login_attempts (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            email CITEXT NOT NULL,
            ip TEXT NOT NULL DEFAULT '',
            succeeded BOOLEAN NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now()
        )
    """)
    connection.exec_driver_sql(
        'CREATE INDEX idx_login_attempts_email ON login_attempts (email, created_at)')
    connection.exec_driver_sql(
        'CREATE INDEX idx_login_attempts_ip ON login_attempts (ip, created_at)')


def downgrade():
    raise RuntimeError('Destructive downgrade forbidden. Restore a backup into a new instance.')

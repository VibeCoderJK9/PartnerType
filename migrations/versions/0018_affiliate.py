"""Affiliate programme: referral links, clicks and shop orders.

A partner shares a personal link. A visitor who buys in the producer's shop
after following it becomes a conversion, reported by the shop through a signed
webhook. An approved conversion becomes a won lead of that partner, so payouts,
statistics and dashboards read it like any other sale.

Personal data stays out: no buyer e-mail, name or IP address and no webhook
body is stored, only the order id, the net amount, its currency and time, the
partner code or click id and a SHA-256 of the body.

The policies follow migration 0016. A partner reads his own link, clicks and
conversions; staff read all of them; the read-only observer has no business
with money (as with payouts); only the instance itself counts a click. The
shared secrets are readable by the instance and the administrator alone.

A refund can reach PartnerType before its order (deliveries are not ordered,
and a refused one is retried later). It is held, with no personal data, until
the order arrives, so that order starts out refunded instead of payable. Only
the instance itself touches those rows.
"""
from alembic import op


revision = '0018_affiliate'
down_revision = '0017_staff_directory'
branch_labels = None
depends_on = None

WRITES_ALL = "app_role() IN ('system','admin','manager')"
PARTNER = "app_role() = 'partner'"
OWN = f"{WRITES_ALL} OR ({PARTNER} AND partner_id = app_user_id())"
SYSTEM = "app_role() = 'system'"
SECRET_HOLDERS = "app_role() IN ('system','admin')"

CONVERSION_STATUSES = (
    'pending', 'unattributed', 'approved', 'rejected', 'refunded',
    'refund_after_approval', 'reversed',
)

TABLES = ('affiliate_links', 'affiliate_clicks', 'affiliate_conversions', 'affiliate_secrets',
          'affiliate_early_refunds')


def _policies():
    """(table, policy name, command, USING, WITH CHECK) for every policy."""
    return [
        ('affiliate_links', 'affiliate_links_select', 'SELECT', OWN, None),
        ('affiliate_links', 'affiliate_links_insert', 'INSERT', None, OWN),
        # A partner creates his link but never rewrites its code or revives
        # a revoked one; changes are the instance's and staff's.
        ('affiliate_links', 'affiliate_links_update', 'UPDATE', WRITES_ALL, WRITES_ALL),
        ('affiliate_links', 'affiliate_links_delete', 'DELETE', WRITES_ALL, None),

        ('affiliate_clicks', 'affiliate_clicks_select', 'SELECT', OWN, None),
        ('affiliate_clicks', 'affiliate_clicks_insert', 'INSERT', None, SYSTEM),
        ('affiliate_clicks', 'affiliate_clicks_update', 'UPDATE', SYSTEM, SYSTEM),
        ('affiliate_clicks', 'affiliate_clicks_delete', 'DELETE', WRITES_ALL, None),

        ('affiliate_conversions', 'affiliate_conversions_select', 'SELECT', OWN, None),
        ('affiliate_conversions', 'affiliate_conversions_insert', 'INSERT', None, WRITES_ALL),
        ('affiliate_conversions', 'affiliate_conversions_update', 'UPDATE', WRITES_ALL, WRITES_ALL),
        ('affiliate_conversions', 'affiliate_conversions_delete', 'DELETE', WRITES_ALL, None),

        ('affiliate_secrets', 'affiliate_secrets_select', 'SELECT', SECRET_HOLDERS, None),
        ('affiliate_secrets', 'affiliate_secrets_insert', 'INSERT', None, SECRET_HOLDERS),
        ('affiliate_secrets', 'affiliate_secrets_update', 'UPDATE', SECRET_HOLDERS, SECRET_HOLDERS),
        ('affiliate_secrets', 'affiliate_secrets_delete', 'DELETE', SECRET_HOLDERS, None),

        ('affiliate_early_refunds', 'affiliate_early_refunds_select', 'SELECT', SYSTEM, None),
        ('affiliate_early_refunds', 'affiliate_early_refunds_insert', 'INSERT', None, SYSTEM),
        ('affiliate_early_refunds', 'affiliate_early_refunds_update', 'UPDATE', SYSTEM, SYSTEM),
        ('affiliate_early_refunds', 'affiliate_early_refunds_delete', 'DELETE', SYSTEM, None),
    ]



"""API gateway: personal keys, OAuth 2.1 grants and tokens, call log, limits."""
from alembic import op


revision = '0013_api_gateway'
down_revision = '0012_blocks'
branch_labels = None
depends_on = None


def upgrade():
    connection = op.get_bind()
    # One external door per instance. Claude (claude.ai,
    # Desktop, phone) connects over OAuth 2.1 and Claude Code with a personal
    # key, both only to /mcp and /api/v1, read-only. Every secret
    # below is stored as its SHA-256 fingerprint and never as itself: reading
    # this database must not hand anyone a working key or token.
    connection.exec_driver_sql("""
        CREATE TABLE api_keys (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 100),
            display_prefix TEXT NOT NULL,
            token_hash TEXT NOT NULL UNIQUE,
            scopes TEXT NOT NULL DEFAULT 'read',
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            expires_at TIMESTAMPTZ NOT NULL,
            last_used_at TIMESTAMPTZ,
            revoked_at TIMESTAMPTZ,
            revoked_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
            CHECK (expires_at > created_at)
        )
    """)
    connection.exec_driver_sql("CREATE INDEX api_keys_user_idx ON api_keys (user_id)")

    # Clients register themselves (RFC 7591) because the claude.ai connector
    # requires it. They are public clients bound by PKCE, so there is no
    # secret column at all -- nothing here could be leaked as a credential.
    connection.exec_driver_sql("""
        CREATE TABLE oauth_clients (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            client_id TEXT NOT NULL UNIQUE,
            client_name TEXT NOT NULL DEFAULT '',
            redirect_uris TEXT NOT NULL,
            application_type TEXT NOT NULL DEFAULT '',
            registered_ip TEXT NOT NULL DEFAULT '',
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            last_used_at TIMESTAMPTZ
        )
    """)

    # A validated /oauth/authorize request waiting for the consent click.
    # Ten minutes, single use.
    connection.exec_driver_sql("""
        CREATE TABLE oauth_authorize_requests (
            request_hash TEXT PRIMARY KEY,
            client_id TEXT NOT NULL REFERENCES oauth_clients(client_id) ON DELETE CASCADE,
            redirect_uri TEXT NOT NULL,
            code_challenge TEXT NOT NULL,
            scope TEXT NOT NULL,
            resource TEXT NOT NULL,
            state TEXT,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            expires_at TIMESTAMPTZ NOT NULL,
            used_at TIMESTAMPTZ
        )
    """)

    # A grant is what the Integrations screen calls "an OAuth connection":
    # one person's consent for one client. Revoking it kills every token it
    # issued.
    connection.exec_driver_sql("""
        CREATE TABLE oauth_grants (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            client_id TEXT NOT NULL REFERENCES oauth_clients(client_id) ON DELETE CASCADE,
            scope TEXT NOT NULL DEFAULT 'read',
            resource TEXT NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            last_used_at TIMESTAMPTZ,
            revoked_at TIMESTAMPTZ,
            revoked_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
            revoked_reason TEXT
        )
    """)
    connection.exec_driver_sql("CREATE INDEX oauth_grants_user_idx ON oauth_grants (user_id)")
    connection.exec_driver_sql("CREATE INDEX oauth_grants_client_idx ON oauth_grants (client_id)")

    connection.exec_driver_sql("""
        CREATE TABLE oauth_codes (
            code_hash TEXT PRIMARY KEY,
            grant_id INTEGER NOT NULL REFERENCES oauth_grants(id) ON DELETE CASCADE,
            client_id TEXT NOT NULL,
            redirect_uri TEXT NOT NULL,
            code_challenge TEXT NOT NULL,
            resource TEXT NOT NULL,
            scope TEXT NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            expires_at TIMESTAMPTZ NOT NULL,
            used_at TIMESTAMPTZ
        )
    """)

    connection.exec_driver_sql("""
        CREATE TABLE oauth_tokens (
            token_hash TEXT PRIMARY KEY,
            grant_id INTEGER NOT NULL REFERENCES oauth_grants(id) ON DELETE CASCADE,
            kind TEXT NOT NULL CHECK (kind IN ('access', 'refresh')),
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            expires_at TIMESTAMPTZ NOT NULL,
            rotated_at TIMESTAMPTZ,
            revoked_at TIMESTAMPTZ
        )
    """)
    connection.exec_driver_sql("CREATE INDEX oauth_tokens_grant_idx ON oauth_tokens (grant_id)")

    # Who called what, when, and how it ended. Deliberately no column for
    # arguments, bodies, URLs or tokens: the log must be safe to show to the
    # administrator and must not become a copy of the CRM.
    connection.exec_driver_sql("""
        CREATE TABLE api_call_log (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            connection_kind TEXT NOT NULL CHECK (connection_kind IN ('key', 'oauth')),
            connection_id INTEGER NOT NULL,
            user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
            surface TEXT NOT NULL CHECK (surface IN ('mcp', 'api_v1')),
            operation TEXT NOT NULL CHECK (length(operation) <= 100),
            status_code INTEGER NOT NULL,
            outcome TEXT NOT NULL CHECK (outcome IN ('ok', 'error', 'denied', 'rate_limited')),
            records INTEGER NOT NULL DEFAULT 0,
            duration_ms INTEGER NOT NULL DEFAULT 0
        )
    """)
    connection.exec_driver_sql("CREATE INDEX api_call_log_created_idx ON api_call_log (created_at)")
    connection.exec_driver_sql(
        "CREATE INDEX api_call_log_connection_idx"
        " ON api_call_log (connection_kind, connection_id, created_at)")

    # Daily usage per connection: the basis for any later paid package.
    connection.exec_driver_sql("""
        CREATE TABLE api_usage_daily (
            connection_kind TEXT NOT NULL,
            connection_id INTEGER NOT NULL,
            day DATE NOT NULL,
            calls INTEGER NOT NULL DEFAULT 0,
            denied INTEGER NOT NULL DEFAULT 0,
            records INTEGER NOT NULL DEFAULT 0,
            PRIMARY KEY (connection_kind, connection_id, day)
        )
    """)

    # Fixed rate-limit windows, kept in the database so a restart does not
    # reset them and every worker thread sees the same count.
    connection.exec_driver_sql("""
        CREATE TABLE api_rate_windows (
            bucket TEXT NOT NULL,
            window_start TIMESTAMPTZ NOT NULL,
            hits INTEGER NOT NULL DEFAULT 0,
            PRIMARY KEY (bucket, window_start)
        )
    """)


def downgrade():
    raise RuntimeError('Destructive downgrade forbidden. Restore a backup into a new instance.')

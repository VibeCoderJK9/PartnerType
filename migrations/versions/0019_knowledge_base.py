"""Knowledge base: documents the producer shares with every partner.

Price lists, product sheets, presentations and contract templates. The file
lives in the database next to everything else, so the existing encrypted
backup and restore carry it with no second storage to manage. Size and type
are checked by api/knowledge.py before a row is written.

The policies follow migration 0016. Nothing here belongs to one partner: every
known role reads every document, and only the producer's staff (and the
instance itself) add, change or remove one.

Downgrading drops the table and every uploaded document with it; only a
backup taken before brings them back (docs/operations/INSTANCES.md).
"""
from alembic import op


revision = '0019_knowledge_base'
down_revision = '0018_affiliate'
branch_labels = None
depends_on = None

KNOWN = "app_role() IN ('system','admin','manager','observer','partner')"
WRITES_ALL = "app_role() IN ('system','admin','manager')"

TABLE = 'knowledge_documents'


def _policies():
    """(policy name, command, USING, WITH CHECK) for every policy."""
    return [
        (f'{TABLE}_select', 'SELECT', KNOWN, None),
        (f'{TABLE}_insert', 'INSERT', None, WRITES_ALL),
        (f'{TABLE}_update', 'UPDATE', WRITES_ALL, WRITES_ALL),
        (f'{TABLE}_delete', 'DELETE', WRITES_ALL, None),
    ]


def upgrade():
    connection = op.get_bind()
    connection.exec_driver_sql(f"""
        CREATE TABLE {TABLE} (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            title TEXT NOT NULL CHECK (length(title) BETWEEN 1 AND 200),
            description TEXT NOT NULL DEFAULT '' CHECK (length(description) <= 1000),
            filename TEXT NOT NULL CHECK (length(filename) BETWEEN 1 AND 200),
            kind TEXT NOT NULL CHECK (kind IN ('pdf', 'docx', 'xlsx', 'pptx', 'png', 'jpeg')),
            size_bytes INTEGER NOT NULL CHECK (size_bytes > 0),
            sha256 TEXT NOT NULL CHECK (sha256 ~ '^[0-9a-f]{{64}}$'),
            content BYTEA NOT NULL,
            uploaded_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
        )
    """)
    connection.exec_driver_sql(
        f'CREATE INDEX {TABLE}_created_idx ON {TABLE} (created_at DESC)')
    connection.exec_driver_sql(f'ALTER TABLE {TABLE} ENABLE ROW LEVEL SECURITY')
    connection.exec_driver_sql(f'ALTER TABLE {TABLE} FORCE ROW LEVEL SECURITY')
    for name, command, using, check in _policies():
        sql = f'CREATE POLICY {name} ON {TABLE} FOR {command}'
        if using:
            sql += f' USING ({using})'
        if check:
            sql += f' WITH CHECK ({check})'
        connection.exec_driver_sql(sql)


def downgrade():
    op.get_bind().exec_driver_sql(f'DROP TABLE IF EXISTS {TABLE}')

"""Second factor: one shared secret per account plus single-use backup codes."""
from alembic import op


revision = '0005_mfa'
down_revision = '0004_session_hardening'
branch_labels = None
depends_on = None


def upgrade():
    connection = op.get_bind()
    # One row per account, created when enrolment starts and only trusted once
    # confirmed_at is set -- a half-finished enrolment must never be able to
    # lock somebody out of their own account.
    connection.exec_driver_sql("""
        CREATE TABLE user_mfa (
            user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
            secret TEXT NOT NULL,
            confirmed_at TEXT,
            created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'))
        )
    """)
    # Hashed like every other secret here: the printed list is the only place
    # the codes exist in readable form.
    connection.exec_driver_sql("""
        CREATE TABLE user_mfa_backup_codes (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            code_hash TEXT NOT NULL,
            used_at TEXT
        )
    """)
    connection.exec_driver_sql(
        'CREATE INDEX idx_mfa_backup_user ON user_mfa_backup_codes (user_id)')
    # The gap between "password accepted" and "code accepted". Kept in the
    # database rather than in process memory so it survives a restart and can
    # be spent exactly once.
    connection.exec_driver_sql("""
        CREATE TABLE mfa_challenges (
            token_hash TEXT PRIMARY KEY,
            user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            expires_at TEXT NOT NULL,
            created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'))
        )
    """)


def downgrade():
    raise RuntimeError('Destructive downgrade forbidden. Restore a backup into a new instance.')

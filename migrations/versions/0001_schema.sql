CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email CITEXT NOT NULL UNIQUE ,
    password TEXT NOT NULL,
    name TEXT NOT NULL,
    role TEXT NOT NULL CHECK(role IN ('admin','partner','manager','observer')),
    company TEXT NOT NULL DEFAULT '',
    level TEXT NOT NULL DEFAULT 'bronze' CHECK(level IN ('bronze','silver','gold','platinum')),
    phone TEXT NOT NULL DEFAULT '',
    bio TEXT NOT NULL DEFAULT '',
    account_status TEXT NOT NULL DEFAULT 'active' CHECK(account_status IN ('active','pending','suspended','rejected')),
    active INTEGER NOT NULL DEFAULT 1,
    created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS')),
    rejected_at TEXT,
    tier_id INTEGER 
);

CREATE TABLE sessions (
    token TEXT PRIMARY KEY,
    user_id INTEGER NOT NULL ,
    expires_at TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE agent_pending_actions (
    token TEXT PRIMARY KEY,
    user_id INTEGER NOT NULL ,
    action_type TEXT NOT NULL,
    payload TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','executing')),
    created_at TEXT NOT NULL,
    expires_at TEXT NOT NULL
);

CREATE TABLE products (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name CITEXT NOT NULL UNIQUE ,
    code CITEXT UNIQUE ,
    category TEXT NOT NULL CHECK(category IN ('Wdrożenie','Licencja','Usługa','Wsparcie')),
    base_price DOUBLE PRECISION CHECK(base_price IS NULL OR base_price >= 0),
    offered INTEGER NOT NULL DEFAULT 0 CHECK(offered IN (0,1)),
    active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1)),
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE notifications (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL ,
    type TEXT NOT NULL DEFAULT 'info',
    title TEXT NOT NULL,
    body TEXT NOT NULL DEFAULT '',
    link TEXT NOT NULL DEFAULT '',
    is_read INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS')),
    title_key TEXT NOT NULL DEFAULT '',
    body_key TEXT NOT NULL DEFAULT '',
    params TEXT NOT NULL DEFAULT ''
);

CREATE TABLE lead_comments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id TEXT NOT NULL ,
    user_id INTEGER NOT NULL ,
    body TEXT NOT NULL,
    is_internal INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL,
    updated_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE audit_log (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER ,
    user_name TEXT NOT NULL DEFAULT '',
    user_role TEXT NOT NULL DEFAULT '',
    action TEXT NOT NULL,
    entity TEXT NOT NULL DEFAULT '',
    entity_id TEXT NOT NULL DEFAULT '',
    detail TEXT NOT NULL DEFAULT '',
    ip TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS')),
    detail_key TEXT NOT NULL DEFAULT '',
    detail_params TEXT NOT NULL DEFAULT ''
);

CREATE TABLE commission_tiers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    base_rate DOUBLE PRECISION NOT NULL DEFAULT 5.0,
    color TEXT NOT NULL DEFAULT '#6246ea',
    sort_order INTEGER NOT NULL DEFAULT 0,
    active INTEGER NOT NULL DEFAULT 1,
    created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE bonus_definitions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    type TEXT NOT NULL DEFAULT 'percent' CHECK(type IN ('percent','cash')),
    default_value DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    description TEXT NOT NULL DEFAULT '',
    sort_order INTEGER NOT NULL DEFAULT 0,
    active INTEGER NOT NULL DEFAULT 1,
    created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS')),
    name_en TEXT NOT NULL DEFAULT '',
    description_en TEXT NOT NULL DEFAULT ''
);

CREATE TABLE partner_bonus_assignments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partner_id INTEGER NOT NULL ,
    bonus_def_id INTEGER NOT NULL ,
    custom_value DOUBLE PRECISION,
    is_active INTEGER NOT NULL DEFAULT 1,
    assigned_by INTEGER ,
    assigned_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS')),
    UNIQUE(partner_id, bonus_def_id)
);

CREATE TABLE partner_invitations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash TEXT NOT NULL UNIQUE,
    user_id INTEGER NOT NULL ,
    created_by INTEGER ,
    expires_at TEXT NOT NULL,
    accepted_at TEXT,
    created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE leads (
    id TEXT PRIMARY KEY,
    client_name TEXT NOT NULL,
    client_email TEXT NOT NULL,
    client_phone TEXT NOT NULL DEFAULT '',
    company TEXT NOT NULL,
    value DOUBLE PRECISION NOT NULL DEFAULT 0,
    notes TEXT NOT NULL DEFAULT '',
    sector TEXT NOT NULL DEFAULT '',
    nip TEXT NOT NULL DEFAULT '',
    website TEXT NOT NULL DEFAULT '',
    product TEXT NOT NULL DEFAULT '',
    product_id INTEGER ,
    quantity INTEGER NOT NULL DEFAULT 0,
    queue_position INTEGER NOT NULL DEFAULT 1,
    status TEXT,
    partner_id INTEGER NOT NULL ,
    commission DOUBLE PRECISION,
    created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS')),
    updated_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS')),
    registration_status TEXT NOT NULL DEFAULT 'pending' CHECK(registration_status IN ('pending','needs_info','accepted','rejected')),
    commission_override_pct DOUBLE PRECISION,
    won_at TEXT,
    revision INTEGER NOT NULL DEFAULT 0,
    settlement_status TEXT,
    settlement_reviewed_by INTEGER ,
    settlement_reviewed_at TEXT,
    settlement_review_reason TEXT,
    commission_paid_at TEXT,
    win_confirmed_at TEXT,
    win_confirmed_by INTEGER 
);

CREATE TABLE lead_stages (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    kind TEXT NOT NULL DEFAULT 'progress' CHECK(kind IN ('progress','win','lose')),
    is_terminal INTEGER NOT NULL DEFAULT 0,
    color TEXT NOT NULL DEFAULT '#6246ea',
    active INTEGER NOT NULL DEFAULT 1,
    created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS')),
    name_en TEXT NOT NULL DEFAULT ''
);

CREATE TABLE registration_fields (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label TEXT NOT NULL,
    max_length INTEGER NOT NULL DEFAULT 200,
    sort_order INTEGER NOT NULL DEFAULT 0,
    active INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS')),
    label_en TEXT NOT NULL DEFAULT ''
);

CREATE TABLE registration_field_values (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL ,
    field_id INTEGER NOT NULL ,
    value TEXT NOT NULL DEFAULT '',
    UNIQUE(user_id, field_id)
);

CREATE TABLE lead_workflow_operations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id INTEGER NOT NULL,
    operation_id TEXT NOT NULL,
    payload_hash TEXT NOT NULL,
    lead_id TEXT NOT NULL,
    result_json TEXT NOT NULL,
    created_at TEXT NOT NULL,
    UNIQUE (actor_id, operation_id)
);

CREATE TABLE lead_workflow_events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id TEXT NOT NULL,
    actor_id INTEGER NOT NULL,
    event_type TEXT NOT NULL,
    payload_json TEXT NOT NULL,
    created_at TEXT NOT NULL
);

CREATE TABLE lead_fields (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label TEXT NOT NULL,
    field_type TEXT NOT NULL DEFAULT 'text',
    required INTEGER NOT NULL DEFAULT 0,
    partner_editable INTEGER NOT NULL DEFAULT 0,
    active INTEGER NOT NULL DEFAULT 1,
    sort_order INTEGER NOT NULL DEFAULT 0,
    revision INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS')),
    label_en TEXT NOT NULL DEFAULT ''
);

CREATE TABLE lead_field_values (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id TEXT NOT NULL,
    field_id INTEGER NOT NULL ,
    value TEXT NOT NULL DEFAULT '',
    UNIQUE(lead_id, field_id)
);

CREATE TABLE commission_payouts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partner_id INTEGER NOT NULL ,
    period_type TEXT NOT NULL CHECK(period_type IN ('month','quarter')),
    period_key TEXT NOT NULL,
    amount DOUBLE PRECISION NOT NULL,
    lead_count INTEGER NOT NULL,
    note TEXT,
    paid_by INTEGER ,
    paid_at TEXT NOT NULL,
    reversed_by INTEGER ,
    reversed_at TEXT
);

CREATE TABLE bonus_awards (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partner_id INTEGER NOT NULL ,
    bonus_def_id INTEGER ,
    name TEXT NOT NULL,
    amount DOUBLE PRECISION NOT NULL,
    note TEXT,
    granted_by INTEGER ,
    granted_at TEXT NOT NULL,
    paid_at TEXT,
    payout_id INTEGER 
);


"""Single-use password reset secrets, kept apart from invitations."""
from alembic import op


revision = '0003_password_resets'
down_revision = '0002_login_attempts'
branch_labels = None
depends_on = None


def upgrade():
    connection = op.get_bind()
    # Not a `purpose` column on partner_invitations: accepting an invitation
    # also activates a pending account, which a reset must never do. Separate
    # tables keep that difference impossible to confuse.
    connection.exec_driver_sql("""
        CREATE TABLE password_resets (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            token_hash TEXT NOT NULL UNIQUE,
            expires_at TEXT NOT NULL,
            used_at TEXT,
            created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'))
        )
    """)
    connection.exec_driver_sql(
        'CREATE INDEX idx_password_resets_user ON password_resets (user_id, created_at)')


